export function creatureTableRow(table, level) {
  return BUILDING_CREATURE_TABLES[table][Math.max(0, Math.min(25, Number(level) + 1))];
}

export function safeItemGuidance(level) {
  const numeric = Math.max(-1, Math.min(24, Number(level)));
  const itemLevel = numeric <= 3 ? 0 : numeric <= 5 ? 1 : numeric - 4;
  const notes = new Map([[6,"+1 weapon"],[8,"+1 striking weapon"],[9,"+1 armor"],[12,"+1 resilient armor"],
    [14,"+2 striking weapon"],[15,"+2 resilient armor"],[16,"+2 greater striking weapon"],[18,"+2 greater resilient armor"],
    [20,"+3 greater striking weapon"],[22,"+3 greater resilient armor"],[23,"+3 major striking weapon"],[24,"+3 major resilient armor"]]);
  return { level: itemLevel, note: notes.get(numeric) ?? "" };
}
